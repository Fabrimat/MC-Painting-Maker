// One-off generator for the default pack icon embedded in createEmptyProject().
// Produces a 64x64 pixel-art painting frame (dark border, wood frame with grain,
// cream canvas) using only Node built-ins, and emits both a PNG file and the
// base64 string copied into src/paintings/defaultPackIcon.ts.
//
// Run with: node scripts/generate-default-pack-icon.mjs
import { writeFileSync } from 'node:fs';
import { deflateSync } from 'node:zlib';

const W = 64;
const H = 64;
const FRAME = 6; // wood frame thickness in pixels

const DARK   = [0x3a, 0x23, 0x0f, 0xff]; // outer + inner rims
const WOOD_A = [0xa1, 0x68, 0x42, 0xff]; // wood base
const WOOD_B = [0x7d, 0x4f, 0x30, 0xff]; // wood grain
const CREAM  = [0xf5, 0xe9, 0xc8, 0xff]; // canvas

function pixelAt(x, y) {
  const onOuterEdge = x === 0 || y === 0 || x === W - 1 || y === H - 1;
  if (onOuterEdge) return DARK;

  const innerX0 = FRAME, innerX1 = W - 1 - FRAME;
  const innerY0 = FRAME, innerY1 = H - 1 - FRAME;
  const onInnerEdge =
    (x === innerX0 || x === innerX1) && (y >= innerY0 && y <= innerY1) ||
    (y === innerY0 || y === innerY1) && (x >= innerX0 && x <= innerX1);
  if (onInnerEdge) return DARK;

  const inFrame = x < innerX0 || x > innerX1 || y < innerY0 || y > innerY1;
  if (inFrame) {
    // Diagonal grain so the frame doesn't read as flat.
    return ((x + y) % 3 === 0) ? WOOD_B : WOOD_A;
  }
  return CREAM;
}

const raw = Buffer.alloc((1 + W * 4) * H);
let off = 0;
for (let y = 0; y < H; y++) {
  raw[off++] = 0; // filter type: None
  for (let x = 0; x < W; x++) {
    const px = pixelAt(x, y);
    raw[off++] = px[0];
    raw[off++] = px[1];
    raw[off++] = px[2];
    raw[off++] = px[3];
  }
}

const CRC_TABLE = (() => {
  const t = new Uint32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) c = (c & 1) ? (0xedb88320 ^ (c >>> 1)) : (c >>> 1);
    t[n] = c >>> 0;
  }
  return t;
})();
function crc32(buf) {
  let c = 0xffffffff;
  for (let i = 0; i < buf.length; i++) {
    c = (CRC_TABLE[(c ^ buf[i]) & 0xff] ^ (c >>> 8)) >>> 0;
  }
  return (c ^ 0xffffffff) >>> 0;
}

function chunk(type, data) {
  const len = Buffer.alloc(4); len.writeUInt32BE(data.length, 0);
  const typ = Buffer.from(type, 'ascii');
  const crcBuf = Buffer.alloc(4);
  crcBuf.writeUInt32BE(crc32(Buffer.concat([typ, data])), 0);
  return Buffer.concat([len, typ, data, crcBuf]);
}

const sig = Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]);
const ihdr = Buffer.alloc(13);
ihdr.writeUInt32BE(W, 0);
ihdr.writeUInt32BE(H, 4);
ihdr[8] = 8;  // bit depth
ihdr[9] = 6;  // color type: RGBA
ihdr[10] = 0; // compression
ihdr[11] = 0; // filter
ihdr[12] = 0; // interlace
const idat = deflateSync(raw, { level: 9 });
const png = Buffer.concat([
  sig,
  chunk('IHDR', ihdr),
  chunk('IDAT', idat),
  chunk('IEND', Buffer.alloc(0)),
]);

const outPng = new URL('./default-pack-icon.png', import.meta.url);
writeFileSync(outPng, png);

const b64 = png.toString('base64');
const tsFile = new URL('../src/paintings/defaultPackIcon.ts', import.meta.url);
const tsBody = `// Generated by scripts/generate-default-pack-icon.mjs — do not edit by hand.
// Re-run the script to regenerate after changing the icon design.
export const DEFAULT_PACK_ICON_BASE64 =
  '${b64}';
`;
writeFileSync(tsFile, tsBody);

process.stdout.write(`Wrote ${png.length} bytes -> scripts/default-pack-icon.png\n`);
process.stdout.write(`Wrote ${b64.length} base64 chars -> src/paintings/defaultPackIcon.ts\n`);
